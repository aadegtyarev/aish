//! Differential freeze of `plan` (argv, or `-`) and `on_hard_list` over tricky
//! inputs: a lexer or table refactor must not move any line. Moved on purpose
//! (one lexer, one secret table): `"a\$b"` keeps no backslash as bash reads it;
//! `#` comments, `\r` and backslash-newline are refused; `2>&'1'` and
//! `2>&1|` mean `2>&1`; searches exclude only the dot secret dirs by name.

use super::*;

#[test]
fn plan_and_hard_list_are_frozen() {
    let h = home();
    let mut bad = Vec::new();
    for (c, want) in FROZEN {
        let a = match plan(c, &[], "/tmp/proj-x") {
            Some(p) => format!("{:?}", p.stages),
            None => "-".to_string(),
        };
        let a = if h.is_empty() {
            a
        } else {
            a.replace(&h, "<H>")
        };
        let got = format!("{a} {}", crate::llm::hard::on_hard_list(c));
        if got != *want {
            bad.push(format!("    ({c:?}, {got:?}),"));
        }
    }
    assert!(bad.is_empty(), "changed rows:\n{}", bad.join("\n"));
}

